import assert from 'node:assert/strict';
import { request } from 'playwright';
const base=process.env.GOOGLE_TEST_BASE??'http://localhost:3001';
const api=await request.newContext({maxRedirects:0});
const start=await api.get(`${base}/api/customer-auth/google?seat=VIP%202`);
assert.equal(start.status(),307);
const destination=new URL(start.headers().location);
assert.equal(destination.hostname,'accounts.google.com');
for(const key of ['state','nonce','code_challenge','client_id','redirect_uri']) assert.ok(destination.searchParams.get(key),`missing ${key}`);
assert.equal(destination.searchParams.get('code_challenge_method'),'S256');
const cookie=start.headers()['set-cookie'];assert.match(cookie,/HttpOnly/i);assert.match(cookie,/SameSite=lax/i);
const invalid=await api.get(`${base}/api/customer-auth/google/callback?state=wrong&code=not-a-real-code`);
assert.equal(invalid.status(),307);assert.match(invalid.headers().location,/\/reserve\?auth=failed/);
assert.match(invalid.headers()['set-cookie'],/Max-Age=0/i);
const missing=await api.get(`${base}/api/customer-auth/google/callback?code=not-a-real-code`);
assert.equal(missing.status(),307);assert.match(missing.headers().location,/auth=failed/);
const logout=await api.post(`${base}/api/customer-auth/logout`,{headers:{origin:'https://attacker.example'}});
assert.equal(logout.status(),403);
console.log('Configured-with-fake-credentials HTTP tests passed: Google redirect, state/nonce/PKCE, cookie flags, invalid callback and cross-origin logout rejection.');
console.log('No Google sign-in was performed.'); await api.dispose();
