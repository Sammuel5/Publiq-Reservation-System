/** Live HTTP + Chromium + MongoDB test. Use a disposable development database. */
import assert from "node:assert/strict";
import { createHash, randomBytes } from "node:crypto";
import mongoose from "mongoose";
import bcrypt from "bcryptjs";
import { chromium } from "playwright";

const base = process.env.TEST_BASE_URL ?? "http://127.0.0.1:3000";
const nonce = randomBytes(3).toString("hex");
const ip1 = `2001:db8:${nonce.slice(0, 4)}::1`;
const ip2 = `2001:db8:${nonce.slice(2, 6)}::1`;
const ip3 = `2001:db9:${nonce.slice(0, 4)}::1`;
const mask = (ip) => `${ip.split(":").slice(0, 3).join(":")}:…`;
const hash = (key) => createHash("sha256").update(key).digest("hex");
const email1 = `countdown-rate-${nonce}@example.test`;
const email2 = `countdown-lock-${nonce}@example.test`;
const email3 = `countdown-other-${nonce}@example.test`;
const password = "Countdown-test-123!";
const keys = [hash(`login:ip:${mask(ip1)}`), hash(`login:ip:${mask(ip2)}`), hash(`login:email:${email1}`), hash(`login:email:${email2}`), hash(`login:ip:${mask(ip3)}`), hash(`login:email:${email3}`)];
let browser;
await mongoose.connect(process.env.MONGODB_URI, { dbName: process.env.MONGODB_DB_NAME ?? "ktv_club" });
const db = mongoose.connection.db;
try {
  browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, extraHTTPHeaders: { "X-Forwarded-For": ip1 } });
  const page = await context.newPage();
  await db.collection("rate_limits").insertOne({ _id: keys[0], count: 10, expiresAt: new Date(Date.now() + 9_000) });
  await page.goto(`${base}/admin/login`);
  await page.locator("#email").fill(email1);
  await page.locator("#password").fill(password);
  const result = page.waitForResponse((r) => r.url().endsWith("/api/auth/login") && r.request().method() === "POST");
  await page.getByRole("button", { name: /^Sign in$/ }).click();
  const response = await result;
  assert.equal(response.status(), 429);
  assert.equal(response.headers()["x-login-limit-scope"], "ip");
  assert.ok(Number(response.headers()["retry-after"]) > 0);
  const timer = page.getByTestId("login-countdown");
  await timer.waitFor();
  const before = await timer.textContent();
  assert.match(before, /^\d+:\d\d$/);
  assert.equal(await page.getByRole("button", { name: /^Sign in$/ }).isDisabled(), true);
  await page.locator("#email").fill(email3);
  assert.equal(await page.getByRole("button", { name: /^Sign in$/ }).isDisabled(), true, "network restriction should apply across accounts");
  await page.waitForTimeout(1200);
  assert.notEqual(await timer.textContent(), before, "timer did not tick");
  await page.reload();
  await timer.waitFor();
  assert.equal(await page.getByRole("button", { name: /^Sign in$/ }).isDisabled(), true, "refresh lost countdown");
  await page.getByText("You can try signing in again.").waitFor({ timeout: 15_000 });
  assert.equal(await page.getByRole("button", { name: /^Sign in$/ }).isEnabled(), true);
  console.log("✓ 429 actual Retry-After, visible ticking countdown, refresh persistence, and re-enable");
  await context.close();

  const passwordHash = await bcrypt.hash(password, 10);
  const other = await db.collection("admin_users").insertOne({ name: "Other Staff", email: email3, role: "STAFF", isActive: true, passwordHash, failedLoginAttempts: 0, lockedUntil: null });
  const locked = await db.collection("admin_users").insertOne({ name: "Countdown Test", email: email2, role: "STAFF", isActive: true, passwordHash, failedLoginAttempts: 0, lockedUntil: new Date(Date.now() + 16_000) });
  const context2 = await browser.newContext({ viewport: { width: 1366, height: 900 }, extraHTTPHeaders: { "X-Forwarded-For": ip2 } });
  const page2 = await context2.newPage();
  await page2.goto(`${base}/admin/login`);
  await page2.locator("#email").fill(email2);
  await page2.locator("#password").fill(password);
  const response2Promise = page2.waitForResponse((r) => r.url().endsWith("/api/auth/login") && r.request().method() === "POST");
  await page2.getByRole("button", { name: /^Sign in$/ }).click();
  const response2 = await response2Promise;
  assert.equal(response2.status(), 423);
  assert.equal(response2.headers()["x-login-limit-scope"], "account");
  assert.ok(Number(response2.headers()["retry-after"]) > 0);
  await page2.getByText("Account temporarily locked").waitFor();
  await page2.getByTestId("login-countdown").waitFor();
  await page2.locator("#email").fill(email3);
  assert.equal(await page2.getByRole("button", { name: /^Sign in$/ }).isEnabled(), true, "another account should not inherit the account lock");
  await page2.getByRole("button", { name: /^Sign in$/ }).click();
  await page2.waitForURL((url) => !url.pathname.startsWith("/admin/login"), { timeout: 15_000 });
  await page2.evaluate(() => fetch("/api/auth/logout", { method: "POST" }));
  await page2.goto(`${base}/admin/login`);
  await page2.locator("#email").fill(email2);
  await page2.locator("#password").fill(password);
  await page2.getByText("Account temporarily locked").waitFor();
  await page2.reload();
  await page2.getByText("Account temporarily locked").waitFor();
  assert.equal(await page2.locator("#email").inputValue(), email2);
  await page2.locator("#password").fill(password);
  await page2.getByText("You can try signing in again.").waitFor({ timeout: 25_000 });
  assert.equal(await page2.getByRole("button", { name: /^Sign in$/ }).isEnabled(), true);
  await page2.getByRole("button", { name: /^Sign in$/ }).click();
  await page2.waitForURL((url) => !url.pathname.startsWith("/admin/login"), { timeout: 15_000 });
  console.log("✓ 423 lock follows one account, another staff account signs in, timer survives refresh and locked account signs in after expiry");
  await db.collection("admin_sessions").deleteMany({ user: { $in: [locked.insertedId, other.insertedId] } });
  await context2.close();

  await db.collection("rate_limits").updateOne({ _id: keys[2] }, { $set: { count: 8, expiresAt: new Date(Date.now() + 9_000) } }, { upsert: true });
  const context3 = await browser.newContext({ extraHTTPHeaders: { "X-Forwarded-For": ip3 } });
  const page3 = await context3.newPage();
  await page3.goto(`${base}/admin/login`);
  await page3.locator("#email").fill(email1);
  await page3.locator("#password").fill(password);
  const thirdResponse = page3.waitForResponse((r) => r.url().endsWith("/api/auth/login") && r.request().method() === "POST");
  await page3.getByRole("button", { name: /^Sign in$/ }).click();
  assert.equal((await thirdResponse).headers()["x-login-limit-scope"], "email");
  await page3.getByText("Too many attempts for this email").waitFor();
  await page3.locator("#email").fill(email3);
  assert.equal(await page3.getByRole("button", { name: /^Sign in$/ }).isEnabled(), true, "email quota should not apply to another email");
  await page3.locator("#email").fill(email1);
  assert.equal(await page3.getByRole("button", { name: /^Sign in$/ }).isDisabled(), true, "email timer should return when switching back");
  console.log("✓ 429 email quota follows the affected email, not other accounts");
  await context3.close();
} finally {
  if (browser) await browser.close();
  const users = await db.collection("admin_users").find({ email: { $in: [email1, email2, email3] } }, { projection: { _id: 1 } }).toArray();
  await db.collection("admin_sessions").deleteMany({ user: { $in: users.map((user) => user._id) } });
  await db.collection("admin_users").deleteMany({ email: { $in: [email1, email2, email3] } });
  await db.collection("rate_limits").deleteMany({ _id: { $in: keys } });
  await mongoose.disconnect();
}
